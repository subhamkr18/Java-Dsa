package Methods;

public class BuiltIn {
    public static void main(String[] args) {
        //Math.sqrt- gives Square of a number
        System.out.println(Math.sqrt(16));
        //Math.cbrt- gives cube root ofa number
        System.out.println(Math.cbrt(81));
        // Math.abs- givs Absolute value convert neg integer to positive
        System.out.println(Math.abs(-654));
        // Math.floor- gives GIF
        System.out.println(Math.floor(-6.8));
        // Math.min- gives min of two nums
        System.out.println(Math.min(10,6));
        //Maath.max- gives max of two nums
        System.out.println(Math.max(5.5,5));
    }
}
